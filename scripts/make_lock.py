"""Write requirements.lock: the exact versions of everything requirements.txt needs, as
installed in the CURRENT environment (code review M-28).

    backend\\.venv\\Scripts\\python.exe scripts\\make_lock.py            # (re)write requirements.lock
    backend\\.venv\\Scripts\\python.exe scripts\\make_lock.py --check    # exit 1 if the file is stale

Install from it with the unchanged requirements file as the source of intent:

    pip install -r requirements.txt -c requirements.lock

Why "as installed" and not a fresh resolve: a fresh resolve picks today's newest releases, which
are not the versions the test suite ran against. This records what was actually tested. The
header states the Python version and platform the lock was made on; packages that exist only on
another platform (for example CUDA wheels of torch on Linux) are not in it, so for a different
Python or OS run this script in an environment built for that target and test it there.

No package is upgraded or installed by this script.
"""

from __future__ import annotations

import argparse
import os
import platform
import re
import sys
from importlib import metadata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REQUIREMENTS = os.path.join(ROOT, "requirements.txt")
LOCK = os.path.join(ROOT, "requirements.lock")


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def read_requirement_names(path: str = REQUIREMENTS) -> list[str]:
    names = []
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.split("#", 1)[0].strip()
            if not line or line.startswith(("-", "http")):
                continue
            m = re.match(r"([A-Za-z0-9][A-Za-z0-9._-]*)", line)
            if m:
                names.append(_norm(m.group(1)))
    return names


def closure(roots: list[str]) -> dict[str, str]:
    """{normalised name: installed version} for `roots` and everything they pull in here.

    Optional extras and requirements whose environment marker is false on this machine are not
    followed. A root that is not installed is an error: the lock would silently omit it."""
    from packaging.requirements import Requirement

    seen: dict[str, str] = {}
    pending = list(roots)
    while pending:
        name = _norm(pending.pop())
        if name in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            if name in roots:
                raise SystemExit(f"{name} is in requirements.txt but is not installed in this environment") from None
            continue                         # a marker-guarded dependency of another platform
        seen[name] = dist.version
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker is not None and not req.marker.evaluate({"extra": ""}):
                continue
            pending.append(req.name)
    return dict(sorted(seen.items()))


def render(pins: dict[str, str]) -> str:
    header = [
        "# requirements.lock - exact versions tested together. Generated by scripts/make_lock.py;",
        "# do not edit by hand. Use:  pip install -r requirements.txt -c requirements.lock",
        f"# Made with Python {platform.python_version()} on {platform.system()} {platform.machine()}.",
        "# For another Python or OS, regenerate in an environment built for it and run the tests there.",
    ]
    return "\n".join(header + [f"{name}=={version}" for name, version in pins.items()]) + "\n"


def body_of(text: str) -> list[str]:
    return [ln for ln in text.splitlines() if ln and not ln.startswith("#")]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write or check requirements.lock.")
    parser.add_argument("--check", action="store_true", help="compare with the installed versions; change nothing")
    args = parser.parse_args(argv)

    pins = closure(read_requirement_names())
    text = render(pins)
    if args.check:
        if not os.path.isfile(LOCK):
            print("requirements.lock does not exist")
            return 1
        with open(LOCK, encoding="utf-8") as fh:
            current = body_of(fh.read())
        if current != body_of(text):
            only_now = sorted(set(body_of(text)) - set(current))
            only_file = sorted(set(current) - set(body_of(text)))
            print(f"requirements.lock is stale: {len(only_now)} installed pin(s) differ, {len(only_file)} locked pin(s) differ")
            return 1
        print(f"requirements.lock matches the installed versions ({len(pins)} packages)")
        return 0
    with open(LOCK, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {LOCK} ({len(pins)} packages, Python {platform.python_version()})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
